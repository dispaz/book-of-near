/** What root "sees" in the enclave's memory: bytes that look random (a fixed illustration, not a dump). */
export function enclaveNoise(lines: number): string[] {
  let x = 0x5eed1e55;
  const byte = () => {
    x = (Math.imul(x, 1103515245) + 12345) >>> 0;
    return ((x >>> 16) & 0xff).toString(16).padStart(2, "0");
  };
  return Array.from({ length: lines }, () => Array.from({ length: 8 }, byte).join(" "));
}

export type Verify =
  { status: "idle" } | { status: "running" } | { status: "done"; ok: boolean; checks: Check[] };

/** The state the reactions and the description read. */
export interface LessonState {
  step: number;
  /** Root has read both machines' memory (step 2). */
  dumped: boolean;
  /** Which sample question was sent. */
  asked: number | null;
  /** The answer has finished arriving. */
  answered: boolean;
  attestation: Attestation | null;
  fetching: boolean;
  verify: Verify;
  /** SHA-256 of the quote (hex), once verified. */
  quoteHash: string | null;
}

/** Scene objects the learner can pick. */
export type Obj = "terminal" | "server" | "enclave" | "root" | "quote" | "seal";

export const PICK_LABELS: Record<Obj, string> = {
  terminal: "Your terminal",
  server: "An ordinary cloud server",
  enclave: "The hardware enclave",
  root: "Root access",
  quote: "The attestation quote",
  seal: "Intel's root certificate",
};

/** One object's reaction: its step action, a "not yet" hint, or a detail. */
export type Reaction = { act?: "dump" | "send" | "fetch" | "verify"; hint?: string; detail?: string };

const short = (hex: string, n = 8) => `${hex.slice(0, n)}…${hex.slice(-n)}`;
const verified = (s: LessonState) => s.verify.status === "done" && s.verify.ok;

export function reactionsFor(s: LessonState): Record<Obj, Reaction> {
  return {
    terminal: terminal(s),
    server: {
      detail: s.dumped
        ? "An ordinary cloud server. As root you read the prompt in its memory, in plain text."
        : "An ordinary cloud server. It decrypts your prompt into its memory to work on it.",
    },
    enclave: {
      detail: `A hardware enclave (Intel TDX): the chip encrypts its memory, so root is locked out.${
        s.answered ? " Your prompt is inside, sealed." : ""
      }`,
    },
    root: root(s),
    quote: quote(s),
    seal: seal(s),
  };
}

function terminal(s: LessonState): Reaction {
  if (s.answered && s.asked !== null)
    return {
      detail: `You asked: "${PROMPTS[s.asked]!.question}" It went over an encrypted channel into the enclave.`,
    };
  if (s.step === PROMPT && s.asked === null) return { act: "send" };
  if (s.asked !== null) return { detail: "The answer is arriving…" };
  return { detail: "Your terminal: where you type a prompt." };
}

function root(s: LessonState): Reaction {
  if (s.dumped)
    return {
      detail: "As root you read the server's memory in plain text. The enclave's memory was noise.",
    };
  if (s.step === HOOK) return { hint: "Not yet: you try root access on step 2." };
  return { act: "dump" };
}

function quote(s: LessonState): Reaction {
  const a = s.attestation;
  if (a && verified(s))
    return {
      detail: `Signed by the chip and chained to Intel's root: verified in your browser.${
        s.quoteHash ? ` Quote SHA-256 ${short(s.quoteHash)}.` : ""
      }`,
    };
  if (a && s.step === VERIFY && s.verify.status !== "running") return { act: "verify" };
  if (a)
    return {
      detail: `Intel TDX quote, ${a.quote.length / 2} bytes: measurements, report data and signatures.`,
    };
  if (s.fetching) return { detail: "Fetching the quote…" };
  if (s.step === QUOTE) return { act: "fetch" };
  if (!s.answered) return { hint: "Send a prompt first." };
  if (s.step < QUOTE) return { hint: "Not yet: you fetch the quote on step 4." };
  return { act: "fetch" };
}

function seal(s: LessonState): Reaction {
  if (verified(s))
    return {
      detail: `Intel SGX Root CA, fingerprint ${short(INTEL_SGX_ROOT_SHA256)}: the root Intel publishes.`,
    };
  if (!s.attestation) return { hint: "Fetch the quote first (step 4)." };
  if (s.step < VERIFY) return { hint: "Not yet: you verify on step 5." };
  if (s.verify.status === "running") return { detail: "Checking the signatures…" };
  return { act: "verify" };
}

/** What the figure shows, in one sentence (the 2D group's label and the 3D description). */
export function describe(s: LessonState): string {
  switch (s.step) {
    case HOOK:
      return "Your terminal on the left. Two places your prompt could go: an ordinary cloud server at the back, open, and a sealed hardware enclave in front.";
    case ENCLAVE:
      return s.dumped
        ? "Root has read both memories: the server's shows your prompt in plain text, the enclave's shows only noise."
        : "Root access, a key, stands between the open server and the sealed enclave.";
    case PROMPT:
      return s.answered
        ? "Your prompt went into the enclave, sealed, and the tutor's answer came back to your terminal."
        : "Your terminal is ready to send a prompt to the enclave.";
    case QUOTE:
      return s.attestation
        ? "The enclave has handed over an attestation quote: a signed slip beside it."
        : "The enclave, sealed. No quote yet.";
    case VERIFY:
      return verified(s)
        ? "The quote is verified: its signatures chain up to Intel's root certificate, the seal on the right."
        : "The quote waits beside Intel's root certificate, to be checked.";
    default:
      return "The book is open at the enclave page.";
  }
}
