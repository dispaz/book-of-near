// Builds contracts/counter/counter.wasm from counter.wat with wabt (no Rust toolchain needed).
// Run: npm run build:counter. The .wasm is committed so tests and lessons need no build step.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import initWabt from "wabt";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "contracts", "counter");
const wabt = await initWabt();
// WebAssembly MVP only: NEAR's runtime rejects bulk memory, sign extension and newer features.
const features = {
  mutable_globals: true,
  sat_float_to_int: false,
  sign_extension: false,
  simd: false,
  threads: false,
  multi_value: false,
  tail_call: false,
  bulk_memory: false,
  reference_types: false,
};
const mod = wabt.parseWat("counter.wat", readFileSync(join(dir, "counter.wat"), "utf8"), features);
mod.validate();
const { buffer } = mod.toBinary({ log: false, write_debug_names: false });
writeFileSync(join(dir, "counter.wasm"), buffer);
console.log(`counter.wasm: ${buffer.length} bytes`);

// The same bytes as a module, so a lesson can bundle them (lesson 3.1 deploys them, also in demo mode,
// with no fetch). counterWasm.test.ts checks it matches the .wasm; DemoChain knows it by its hash.
const b64 = Buffer.from(buffer).toString("base64");
const lines = b64.match(/.{1,96}/g) ?? [];
const out = join(dir, "..", "..", "src", "chain", "counterWasm.ts");
writeFileSync(
  out,
  [
    "// Generated by `npm run build:counter` from contracts/counter/counter.wat. Do not edit.",
    "/** contracts/counter/counter.wasm, base64. */",
    "export const COUNTER_WASM_BASE64 =",
    ...lines.map((l, i) => `  "${l}"${i === lines.length - 1 ? ";" : " +"}`),
    "",
  ].join("\n"),
);
console.log(`src/chain/counterWasm.ts: ${b64.length} base64 characters`);
